CREATE TABLE "organization" (
	"id" integer PRIMARY KEY DEFAULT 1 NOT NULL,
	"name" text NOT NULL,
	"street" text NOT NULL,
	"house_number" text NOT NULL,
	"postal_code" text NOT NULL,
	"town" text NOT NULL,
	"country" text NOT NULL,
	"email" text NOT NULL,
	"phone" text,
	"website" text,
	"logo_path" text,
	"iban" text,
	"is_qr_iban" boolean DEFAULT false NOT NULL,
	"default_currency" text DEFAULT 'CHF' NOT NULL,
	"timezone" text DEFAULT 'Europe/Zurich' NOT NULL,
	"default_locale" text DEFAULT 'it' NOT NULL,
	"enabled_locales" jsonb DEFAULT '["it"]'::jsonb NOT NULL,
	"terminology" jsonb DEFAULT '{}'::jsonb NOT NULL,
	"vat_enabled" boolean DEFAULT false NOT NULL,
	"vat_number" text,
	"fiscal_year_start_month" integer DEFAULT 1 NOT NULL,
	"invoice_number_pattern" text DEFAULT '{year}-{seq:04}' NOT NULL,
	"invoice_default_due_days" integer DEFAULT 30 NOT NULL,
	"setup_completed_at" timestamp with time zone,
	"created_at" timestamp with time zone DEFAULT now() NOT NULL,
	"updated_at" timestamp with time zone DEFAULT now() NOT NULL,
	CONSTRAINT "organization_singleton" CHECK ("organization"."id" = 1)
);
